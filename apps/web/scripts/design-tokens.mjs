// Generate the client's design tokens from the design system's tokens.json, so the two
// cannot drift (user, 6 November 2026). Writes:
//   src/styles/tokens.css   custom properties for both themes (dark default) + type classes
//   src/styles/tokens.ts    resolved colours per theme (map style, theme-color meta)
//   public/theme.js         applies the stored theme before first paint (no flash)
// `node scripts/design-tokens.mjs --check` fails when a written file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** The design system the tokens come from (the user's own Design System artifact). */
export const DESIGN_SYSTEM = {
  url: "https://claude.ai/artifact/P3US2NygmWPs1iALn555PU",
  version: "1793960704-e716",
  read: "2026-11-06",
  bundleSha256: "9df5622c8d135fb2b9de49c5cf74d5d15aa0b123364200156be3844253f88221",
  /** The checked-in copies are ahead of the artifact: the user's 11 November look was applied here first. */
  localRevision: "2026-11-11 printed-map look (tokens.json meta.look)",
};

const root = new URL("../", import.meta.url);
const SOURCE = "src/styles/design-system/tokens.json";
const STORAGE_KEY = "opentransit";
const THEMES = ["dark", "light"];
export const DEFAULT_THEME = "dark";

function header(tokens, comment) {
  return [
    `${comment} GENERATED by scripts/design-tokens.mjs from ${SOURCE}; do not edit by hand.`,
    `${comment} Design system: ${tokens.name} ${DESIGN_SYSTEM.url} (version ${DESIGN_SYSTEM.version}, read ${DESIGN_SYSTEM.read}; tokens synced ${tokens.meta.synced}; local revision ${DESIGN_SYSTEM.localRevision}).`,
  ];
}

const alias = (value) => /^\{([a-z0-9-]+)\}$/.exec(value)?.[1] ?? null;

/** A colour's value in a theme, following `{alias}` references to a literal. */
function resolve(byName, name, theme, seen = new Set()) {
  if (seen.has(name)) throw new Error(`alias cycle at ${name}`);
  seen.add(name);
  const token = byName.get(name);
  if (!token) throw new Error(`unknown colour token ${name}`);
  const value = token.value[theme];
  const target = alias(value);
  return target ? resolve(byName, target, theme, seen) : value;
}

function colourLines(tokens, theme) {
  return tokens.color.tokens.map(({ name, value }) => {
    const target = alias(value[theme]);
    return `  --${name}: ${target ? `var(--${target})` : value[theme]};`;
  });
}

function shadowLines(tokens, theme) {
  return tokens.shadow.tokens.map(({ name, value }) => `  --${name}: ${value[theme]};`);
}

export function generate(tokens) {
  for (const theme of THEMES) {
    if (!tokens.color.themes.some((t) => t.id === theme)) throw new Error(`tokens.json has no ${theme} theme`);
  }
  const styles = tokens.type.groups.flatMap((group) => group.styles);
  const typeVars = styles.flatMap((s) => [
    `  --${s.name}-size: ${s.fontSize};`,
    `  --${s.name}-line: ${s.lineHeight};`,
    `  --${s.name}-weight: ${s.fontWeight};`,
    ...(s.letterSpacing ? [`  --${s.name}-tracking: ${s.letterSpacing};`] : []),
  ]);
  const typeClasses = styles.map((s) =>
    [
      `.type-${s.name} {`,
      `  font-size: var(--${s.name}-size);`,
      `  line-height: var(--${s.name}-line);`,
      `  font-weight: var(--${s.name}-weight);`,
      ...(s.letterSpacing ? [`  letter-spacing: var(--${s.name}-tracking);`] : []),
      "}",
    ].join("\n"),
  );
  const light = THEMES[1];
  const css = [
    ...header(tokens, "/*").map((line) => `${line} */`),
    `/* Dark is the default whatever the device prefers (user, 6 November 2026); light applies under data-theme="light", chosen in Settings. */`,
    ":root {",
    `  color-scheme: ${DEFAULT_THEME};`,
    "",
    ...Object.entries(tokens.type.families).map(([name, value]) => `  --font-${name}: ${value};`),
    "",
    ...colourLines(tokens, DEFAULT_THEME),
    "",
    ...shadowLines(tokens, DEFAULT_THEME),
    "",
    ...typeVars,
    "",
    ...tokens.spacing.tokens.map(({ name, value }) => `  --${name}: ${value};`),
    "",
    ...tokens.radius.tokens.map(({ name, value }) => `  --${name}: ${value};`),
    "",
    ...tokens.size.tokens.map(({ name, value }) => `  --${name}: ${value};`),
    "}",
    "",
    `:root[data-theme="${light}"] {`,
    `  color-scheme: ${light};`,
    "",
    ...colourLines(tokens, light),
    "",
    ...shadowLines(tokens, light),
    "}",
    "",
    ...typeClasses.flatMap((block) => [block, ""]),
  ].join("\n");

  const byName = new Map(tokens.color.tokens.map((t) => [t.name, t]));
  const colours = Object.fromEntries(
    THEMES.map((theme) => [theme, Object.fromEntries(tokens.color.tokens.map(({ name }) => [name, resolve(byName, name, theme)]))]),
  );
  const names = tokens.color.tokens.map(({ name }) => JSON.stringify(name));
  const ts = [
    ...header(tokens, "//"),
    "",
    'export type ThemeName = "dark" | "light";',
    `export const DEFAULT_THEME: ThemeName = ${JSON.stringify(DEFAULT_THEME)};`,
    `export const THEMES: readonly ThemeName[] = ${JSON.stringify(THEMES)};`,
    `export type ColorToken =\n  | ${names.join("\n  | ")};`,
    "",
    "/** Every colour token resolved to its literal value, per theme. */",
    `export const THEME_COLORS: Record<ThemeName, Record<ColorToken, string>> = ${JSON.stringify(colours, null, 2)};`,
    "",
  ].join("\n");

  const js = [
    ...header(tokens, "//"),
    "// Applies the stored theme before first paint: dark unless light was chosen in Settings.",
    "/* global document */",
    "(function () {",
    `  var theme = ${JSON.stringify(DEFAULT_THEME)};`,
    "  try {",
    `    var state = JSON.parse(localStorage.getItem(${JSON.stringify(STORAGE_KEY)}) || "null");`,
    `    if (state && state.settings && state.settings.theme === ${JSON.stringify(light)}) theme = ${JSON.stringify(light)};`,
    "  } catch {",
    "    // Storage blocked or unreadable: keep the default.",
    "  }",
    '  document.documentElement.setAttribute("data-theme", theme);',
    "  var meta = document.querySelector('meta[name=\"theme-color\"]');",
    `  if (meta) meta.setAttribute("content", theme === ${JSON.stringify(light)} ? ${JSON.stringify(colours.light.bg)} : ${JSON.stringify(colours.dark.bg)});`,
    "})();",
    "",
  ].join("\n");

  return { "src/styles/tokens.css": css, "src/styles/tokens.ts": ts, "public/theme.js": js };
}

function readIfPresent(url) {
  try {
    return readFileSync(url, "utf8");
  } catch {
    return null;
  }
}

export function readTokens() {
  return JSON.parse(readFileSync(new URL(SOURCE, root), "utf8"));
}

function main() {
  const check = process.argv.includes("--check");
  const files = generate(readTokens());
  const stale = [];
  for (const [path, content] of Object.entries(files)) {
    const url = new URL(path, root);
    if (readIfPresent(url) === content) continue;
    if (check) stale.push(path);
    else writeFileSync(url, content);
  }
  if (stale.length) {
    console.error(`Out of date (run npm run tokens): ${stale.join(", ")}`);
    process.exit(1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
